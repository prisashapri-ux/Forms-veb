export const homeById = (id) => HOME.find((h) => h.id === id) || null;

/**
 * Нагрузка растёт сама: каждые 3 тренировки по комплексу (примерно неделя) уровень +1, всего 4 уровня.
 * Уровень даёт +5 с работы и −5 с отдыха (не меньше 10 с). Растяжку и заминку не трогаем.
 */
export const HOME_LEVEL_EVERY = 3;
export function homeLevel(done) { return Math.min(4, 1 + Math.floor(Math.max(0, done) / HOME_LEVEL_EVERY)); }
export function homeScaled(plan, done) {
  const level = homeLevel(done);
  if (plan.group === 'care' || level === 1) return { ...plan, level0: plan.level, stage: plan.group === 'care' ? 0 : 1, done };
  const k = level - 1;
  return {
    ...plan, level0: plan.level, stage: level, done,
    rest: Math.max(Math.min(10, plan.rest), plan.rest - 5 * k),
    roundRest: plan.roundRest ? Math.max(30, plan.roundRest - 10 * k) : 0,
    items: plan.items.map(([ex, sec]) => [ex, sec + 5 * k]),
  };
}

/** Шаги плеера: подготовка, работа, отдых. */
export function homeSteps(plan, ready = 5) {
  const steps = [{ kind: 'ready', dur: ready, ex: plan.items[0][0], round: 1 }];
  for (let r = 1; r <= plan.rounds; r++) {
    plan.items.forEach(([ex, sec], i) => {
      steps.push({ kind: 'work', dur: sec, ex, round: r });
      const lastInRound = i === plan.items.length - 1;
      const last = lastInRound && r === plan.rounds;
      if (last) return;
      const rest = lastInRound ? plan.roundRest : plan.rest;
      if (rest > 0) steps.push({ kind: 'rest', dur: rest, ex: lastInRound ? plan.items[0][0] : plan.items[i + 1][0], round: r, roundEnd: lastInRound });
    });
  }
  return steps;
}

/** Длительность в минутах, с округлением вверх. */
export function homeMinutes(plan) {
  const s = homeSteps(plan, 0).reduce((a, x) => a + x.dur, 0);
  return Math.ceil(s / 60);
}

/** Тренировка для дневника из выполненных шагов работы. */
export function homeWorkout(plan, doneSteps, startedAt, endedAt, uid) {
  const byName = new Map();
  for (const s of doneSteps) {
    if (!byName.has(s.ex)) byName.set(s.ex, []);
    byName.get(s.ex).push({ weight: 0, reps: s.dur, ...(s.count > 0 ? { count: s.count } : {}), isWarmup: false, isDone: true });
  }
  const mins = Math.max(1, Math.round((endedAt - startedAt) / 60000));
  return {
    id: uid, date: new Date(startedAt).toISOString(), title: `Дома: ${plan.title}`, note: '', durationMinutes: mins,
    programID: `home:${plan.id}`, programDay: null, finishedAt: new Date(endedAt).toISOString(),
    exercises: [...byName.entries()].map(([name, sets]) => ({ name, sets })),
  };
}
